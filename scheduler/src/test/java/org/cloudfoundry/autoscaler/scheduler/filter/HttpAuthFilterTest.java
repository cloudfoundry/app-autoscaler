package org.cloudfoundry.autoscaler.scheduler.filter;

import static org.assertj.core.api.AssertionsForClassTypes.assertThat;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import jakarta.servlet.FilterChain;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.stream.Stream;
import org.cloudfoundry.autoscaler.scheduler.conf.CfHttpConfiguration;
import org.cloudfoundry.autoscaler.scheduler.conf.CfServerConfiguration;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.springframework.mock.web.MockHttpServletRequest;
import org.springframework.mock.web.MockHttpServletResponse;

class HttpAuthFilterTest {

  // Generated by scheduler/scripts/generate_unit_test_certs.sh (make test-certificates).
  // Subject OU carries the literal "OU=space:validspace+OU=organization:validorg", mirroring
  // the CF app-identity cert format the filter substring-matches against.
  private static final String VALID_OU_CERT = readCertResource("/certs/xfcc-valid.crt");

  // Valid base64 but not valid certificate
  private static final String BAD_DER_CERT =
      Base64.getEncoder().encodeToString("not-a-certificate".getBytes(StandardCharsets.UTF_8));

  // Not even valid base64
  private static final String NOT_BASE64_CERT = "@@@ this is not base64 @@@";

  private static final String HEALTH_USERNAME = "test-user";
  private static final String HEALTH_PASSWORD = "test-password";

  // Local port the CF connector listens on; requests arriving here are XFCC-authorized.
  private static final int CF_PORT = 8080;
  // Local port the BOSH (direct mTLS) connector listens on; requests here are exempt from XFCC.
  private static final int BOSH_PORT = 6102;

  private MockHttpServletRequest request;
  private MockHttpServletResponse response;

  private FilterChain filterChain;
  private HttpAuthFilter httpAuthFilter;

  private CfServerConfiguration cfServerConfiguration;
  private CfHttpConfiguration cfHttpConfiguration;

  private static String readCertResource(String resourcePath) {
    try (InputStream in = HttpAuthFilterTest.class.getResourceAsStream(resourcePath)) {
      if (in == null) {
        throw new IllegalStateException(
            "Missing test cert "
                + resourcePath
                + " — run `make scheduler.test-certificates` to generate it");
      }
      return new String(in.readAllBytes(), StandardCharsets.UTF_8);
    } catch (IOException e) {
      throw new IllegalStateException("Failed to read test cert " + resourcePath, e);
    }
  }

  @BeforeEach
  void setup() {
    request = new MockHttpServletRequest();
    response = new MockHttpServletResponse();
    filterChain = mock(FilterChain.class);

    cfServerConfiguration = mock(CfServerConfiguration.class);
    CfServerConfiguration.HealthServer healthServerConfig =
        mock(CfServerConfiguration.HealthServer.class);

    when(healthServerConfig.getUsername()).thenReturn(HEALTH_USERNAME);
    when(healthServerConfig.getPassword()).thenReturn(HEALTH_PASSWORD);

    when(cfServerConfiguration.getHealthserver()).thenReturn(healthServerConfig);

    cfHttpConfiguration = mock(CfHttpConfiguration.class);
    when(cfHttpConfiguration.getPort()).thenReturn(CF_PORT);

    // Default to the CF port so the XFCC-path tests below exercise authorization. Tests covering
    // the BOSH port override the local port explicitly.
    request.setLocalPort(CF_PORT);

    httpAuthFilter = new HttpAuthFilter(cfServerConfiguration, cfHttpConfiguration);
  }

  private static String basicAuth(String raw) {
    return "Basic " + Base64.getEncoder().encodeToString(raw.getBytes());
  }

  @Test
  void testDoFilterWithMissingXfccHeaderReturnsUnauthorized() throws Exception {
    request.setRequestURI("/v1/apps/an-app-guid/schedules");
    request.setMethod("PUT");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(401);
    verify(filterChain, never()).doFilter(request, response);
  }

  @Test
  void testDoFilterWithEmptyXfccHeaderReturnsUnauthorized() throws Exception {
    request.setRequestURI("/v1/apps/an-app-guid/schedules");
    request.setMethod("PUT");
    request.addHeader("X-Forwarded-Client-Cert", "");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(401);
    verify(filterChain, never()).doFilter(request, response);
  }

  private static Stream<Arguments> orgAndSpaceValidityCases() {
    return Stream.of(
        Arguments.of("invalid org and space", false, false),
        Arguments.of("invalid org only", false, true),
        Arguments.of("invalid space only", true, false),
        Arguments.of("valid org and space", true, true));
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("orgAndSpaceValidityCases")
  void testDoFilterWithXfccHeaderChecksOrgAndSpaceValidity(
      String scenario, boolean validOrg, boolean validSpace) throws Exception {
    when(cfServerConfiguration.getValidOrgGuid())
        .thenReturn(validOrg ? "validorg" : "a-different-org");
    when(cfServerConfiguration.getValidSpaceGuid())
        .thenReturn(validSpace ? "validspace" : "a-different-space");
    request.addHeader("X-Forwarded-Client-Cert", VALID_OU_CERT);

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    if (validOrg && validSpace) {
      assertThat(response.getStatus()).isEqualTo(200);
      verify(filterChain).doFilter(request, response);
    } else {
      assertThat(response.getStatus()).isEqualTo(403);
      assertThat(response.getErrorMessage()).isEqualTo("Unauthorized OrganizationalUnit");
      verify(filterChain, never()).doFilter(request, response);
    }
  }

  @Test
  void testDoFilterWithBadDerCertReturnsBadRequestAndDoesNotForward() throws Exception {
    request.addHeader("X-Forwarded-Client-Cert", BAD_DER_CERT);

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(400);
    assertThat(response.getErrorMessage()).contains("Invalid certificate");
    verify(filterChain, never()).doFilter(request, response);
  }

  @Test
  void testDoFilterWithNonBase64CertReturnsBadRequestAndDoesNotForward() throws Exception {
    request.addHeader("X-Forwarded-Client-Cert", NOT_BASE64_CERT);

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(400);
    assertThat(response.getErrorMessage()).contains("Invalid certificate");
    verify(filterChain, never()).doFilter(request, response);
  }

  // --- BOSH (direct mTLS) port exemption ------------------------------------

  @Test
  void testDoFilterOnBoshPortWithoutXfccHeaderForwards() throws Exception {
    // The BOSH port is authenticated by mTLS at the TLS layer; no XFCC header is present and the
    // request must still be forwarded rather than rejected with 401.
    request.setLocalPort(BOSH_PORT);
    request.setRequestURI("/v1/apps/an-app-guid/schedules");
    request.setMethod("PUT");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(200);
    verify(filterChain).doFilter(request, response);
  }

  @Test
  void testDoFilterOnBoshPortIgnoresInvalidXfccHeader() throws Exception {
    // Even a malformed XFCC header must not cause rejection on the BOSH port; it is simply not
    // inspected there.
    request.setLocalPort(BOSH_PORT);
    request.setRequestURI("/v1/apps/an-app-guid/schedules");
    request.setMethod("PUT");
    request.addHeader("X-Forwarded-Client-Cert", BAD_DER_CERT);

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(200);
    verify(filterChain).doFilter(request, response);
  }

  @Test
  void testDoFilterWithNoCfConnectorConfiguredForwards() throws Exception {
    // cfPort == 0 means no CF connector exists (pure BOSH deployment); every request is exempt.
    when(cfHttpConfiguration.getPort()).thenReturn(0);
    request.setLocalPort(BOSH_PORT);
    request.setRequestURI("/v1/apps/an-app-guid/schedules");
    request.setMethod("PUT");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(200);
    verify(filterChain).doFilter(request, response);
  }

  // --- /health basic-auth path ----------------------------------------------

  @Test
  void testDoFilterHttpHealthReturnsSuccess() throws Exception {
    request.setScheme("http");
    request.setRequestURI("/health");
    request.setMethod("GET");
    request.addHeader("Authorization", basicAuth(HEALTH_USERNAME + ":" + HEALTH_PASSWORD));

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(200);
    verify(filterChain, never()).doFilter(request, response);
  }

  @Test
  void testDoFilterHttpHealthMissingAuthorizationHeaderReturnsUnauthorized()
      throws Exception {
    request.setRequestURI("/health");
    request.setMethod("GET");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(401);
    assertThat(response.getErrorMessage()).isEqualTo("Unauthorized");
  }

  @Test
  void testDoFilterHttpHealthNonBasicAuthorizationHeaderReturnsUnauthorized()
      throws Exception {
    request.setRequestURI("/health");
    request.setMethod("GET");
    request.addHeader("Authorization", "Bearer some-token");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(401);
    assertThat(response.getErrorMessage()).isEqualTo("Unauthorized");
  }

  @Test
  void testDoFilterHttpHealthMalformedBase64ReturnsBadRequest() throws Exception {
    request.setRequestURI("/health");
    request.setMethod("GET");
    request.addHeader("Authorization", "Basic !!!not-base64!!!");

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(400);
    assertThat(response.getErrorMessage()).isEqualTo("Bad Request");
  }

  @Test
  void testDoFilterHttpHealthCredentialsWithoutColonReturnsBadRequest() throws Exception {
    request.setRequestURI("/health");
    request.setMethod("GET");
    request.addHeader("Authorization", basicAuth("nocolonhere"));

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(400);
    assertThat(response.getErrorMessage()).isEqualTo("Bad Request");
  }

  @Test
  void testDoFilterHttpHealthWrongUsernameReturnsUnauthorized() throws Exception {
    request.setRequestURI("/health");
    request.setMethod("GET");
    request.addHeader("Authorization", basicAuth("wrong-user:" + HEALTH_PASSWORD));

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(401);
    assertThat(response.getErrorMessage()).isEqualTo("Unauthorized");
  }

  @Test
  void testDoFilterHttpHealthWrongPasswordReturnsUnauthorized() throws Exception {
    // Correct username, wrong password: covers the second half of the credential OR branch.
    request.setRequestURI("/health");
    request.setMethod("GET");
    request.addHeader("Authorization", basicAuth(HEALTH_USERNAME + ":wrong-password"));

    httpAuthFilter.doFilterInternal(request, response, filterChain);

    assertThat(response.getStatus()).isEqualTo(401);
    assertThat(response.getErrorMessage()).isEqualTo("Unauthorized");
  }
}
